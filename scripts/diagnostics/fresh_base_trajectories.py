"""Base collaborations of a run generated anew by its base Agent (diagnostic runs with another Agent backbone)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from src.common.config import IntegrationUnavailable
from src.common.main_config import load_main_config, open_run
from src.grpo.trainer import checkpoint_trajectories, trajectories_path

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", required=True)
    parser.add_argument("--run-id", required=True)
    args = parser.parse_args()
    config = open_run(load_main_config(args.config, ROOT, []), ROOT, run_id=args.run_id, resume=True)
    path = trajectories_path(config, ROOT, 0)
    if path.exists():
        raise IntegrationUnavailable(f"{path} exists; base trajectories are written once per run")
    path.parent.mkdir(parents=True, exist_ok=True)
    result = checkpoint_trajectories(config, ROOT, None, output=path)
    print(json.dumps(dict(result, path=str(path.relative_to(ROOT)), source="generated by the run's base Agent"), indent=1))


if __name__ == "__main__":
    main()
