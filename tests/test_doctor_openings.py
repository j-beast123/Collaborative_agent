def test_trainer_binds_only_the_pinned_table_and_resume_checks_it(tmp_path):
    from test_tree_v1 import arm_trainer
    from src.online_rl.tree import trainer as TT
    tr, *_ = arm_trainer(tmp_path / 'a', 'outcome_only')
    cfg = {**tr.cfg, 'rollout': {**tr.cfg['rollout'], 'doctor_opening': SPEC}}
    kw = dict(out_dir=tmp_path / 'b', cases=list(tr.cases.values()), strategies=tr.st, search_backend=tr.backend, initial_prompt='P0',
              policy_sha=tr.policy_sha, protocol_sha='proto', feedback_prompt_sha256='fb', updater=tr.updater, evaluator=tr.evaluator)
    with pytest.raises(ValueError, match='no frozen opening table is bound'): TT.TreeTrainer(cfg, env=tr.env, **kw)
    wrong = type('T', (), {'sha256': 'f' * 64, '__call__': lambda self, c, s: None})()
    import dataclasses
    with pytest.raises(ValueError, match='not the pinned training table'): TT.TreeTrainer(cfg, env=dataclasses.replace(tr.env, opening=wrong), **kw)
    with pytest.raises(ValueError, match='rollout.doctor_opening is not set'): TT.TreeTrainer(tr.cfg, env=dataclasses.replace(tr.env, opening=wrong), **kw)
    right = type('T', (), {'sha256': 'a' * 64, '__call__': lambda self, c, s: None})()
    t2 = TT.TreeTrainer(cfg, env=dataclasses.replace(tr.env, opening=right), **{**kw, 'initial_prompt': tr.store.get(tr.state.prompt_sha256)})
    man = json.loads((tmp_path / 'b' / 'run_manifest.json').read_text())
    assert man['doctor_opening']['doctor_opening_mode'] == DO.MODE and man['doctor_opening']['train_table_sha256'] == 'a' * 64
    man['doctor_opening']['train_table_sha256'] = 'e' * 64; (tmp_path / 'b' / 'run_manifest.json').write_text(json.dumps(man))
    with pytest.raises(RuntimeError, match='Doctor-opening protocol'):
        TT.TreeTrainer(cfg, env=dataclasses.replace(tr.env, opening=right), **{**kw, 'initial_prompt': t2.store.get(t2.state.prompt_sha256)})
