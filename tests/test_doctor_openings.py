"""Frozen shared Doctor openings (src/online_rl/doctor_openings.py, doctor_opening_mode = frozen_shared_v1): D1 is read from
an immutable per-split table, identical across arms / policies / checkpoints, never regenerated; D2+ stay per run.
A deliberately non-deterministic fake Ollama (every reply carries a call counter) makes any regeneration visible."""
