def test_missing_corrupt_or_mismatched_record_fails_and_never_regenerates(tmp_path):
    path, sha = table(tmp_path); fake = Noisy(); doc = doctor(fake); t = DO.OpeningTable(path, sha, 'train', doc, 5)
    with pytest.raises(DO.OpeningError, match='no frozen D1'): t({**CASE, 'case_id': 'other'}, DO.train_seed(CFG, 'other'))
    with pytest.raises(DO.OpeningError, match='input_sha256|case_sha256'): t({**CASE, 'question': 'changed?'}, DO.train_seed(CFG, 'c1'))
    with pytest.raises(DO.OpeningError, match='seed'): t(CASE, 12345)
    with pytest.raises(DO.OpeningError, match='another Doctor protocol'): DO.OpeningTable(path, sha, 'train', D_sys(Noisy()), 5)
    with pytest.raises(DO.OpeningError, match='split'): DO.OpeningTable(path, sha, 'val50', doc, 5)
    with pytest.raises(DO.OpeningError, match='rounds'): DO.OpeningTable(path, sha, 'train', doc, 4)
    with pytest.raises(DO.OpeningError, match='missing'): DO.OpeningTable(tmp_path / 'nope.json', sha, 'train', doc, 5)
    body = json.loads(path.read_text()); body['records'][0]['visible'] += ' tampered'
    bad = tmp_path / 'bad.json'; bad.write_text(json.dumps(body))
    with pytest.raises(DO.OpeningError, match='corrupt'): DO.OpeningTable(bad, DO.file_sha256(bad), 'train', doc, 5)
    assert fake.chats == []                                                  # nothing was generated on any failure
    with pytest.raises(DO.OpeningError, match='never overwritten'): DO.write_table(path, 'train', doc, 5, [], {})


def test_table_sha_is_verified_at_every_load(tmp_path):
    path, sha = table(tmp_path); doc = doctor(Noisy())
    path.chmod(0o644); path.write_text(path.read_text().replace('"test": true', '"test": false', 1))
    with pytest.raises(DO.OpeningError, match='differs from the pinned'): DO.OpeningTable(path, sha, 'train', doc, 5)


SPEC = {'mode': DO.MODE, 'schema': DO.SCHEMA, 'train_table': 't.json', 'train_table_sha256': 'a' * 64, 'eval_table': 'e.json', 'eval_table_sha256': 'b' * 64}


def test_old_and_new_d1_protocols_never_share_cache_or_evaluations(tmp_path):
    from src.online_rl.integrated.continuation import protocol_sha256
    cfg = json.loads((ROOT / 'configs/online_rl/tree_v1.json').read_text()); ro = {k: v for k, v in cfg['rollout'].items() if k != 'doctor_opening'}
    old = protocol_sha256({**cfg, 'rollout': ro}, ROOT); new = protocol_sha256({**cfg, 'rollout': {**ro, 'doctor_opening': SPEC}}, ROOT)
    other = protocol_sha256({**cfg, 'rollout': {**ro, 'doctor_opening': {**SPEC, 'eval_table_sha256': 'c' * 64}}}, ROOT)
    moved = protocol_sha256({**cfg, 'rollout': {**ro, 'doctor_opening': {**SPEC, 'train_table': 'elsewhere.json'}}}, ROOT)
    assert len({old, new, other}) == 3 and moved == new                      # table identity, not its path
    with pytest.raises(ValueError): protocol_sha256({**cfg, 'rollout': {**ro, 'doctor_opening': {**SPEC, 'mode': 'lazy'}}}, ROOT)
    from src.online_rl.tree.evaluation import MilestoneEvaluator
    play = lambda case, seed: {'final_option': 'B', 'termination_reason': 'doctor_halt', 'num_discussion_rounds': 2}
    prov = {'checkpoint_sha256': 'ck', 'policy_sha256': 'ck', 'prompt_id': None, 'prompt_sha256': None, 'config_sha256': None}
    cases = [{**CASE, 'case_id': f'v{i}'} for i in range(2)]
    MilestoneEvaluator(play, lambda c, o: 1.0, cases, 'val50', 'm', old, 0)(milestone=0, checkpoint=Path('x'), out_dir=tmp_path / 'ev', provenance=prov)
    with pytest.raises(RuntimeError, match='another checkpoint or protocol'):
        MilestoneEvaluator(play, lambda c, o: 1.0, cases, 'val50', 'm', new, 0)(milestone=0, checkpoint=Path('x'), out_dir=tmp_path / 'ev', provenance=prov)


