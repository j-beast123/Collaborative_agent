CFG = {'schedule': {'seed': 3}, 'evaluation': {'seed': 7}}


class Noisy(FakeOllama):
    """Same prompt + seed -> a different text on every call (runtime nondeterminism); settled status from turn 2."""
    def __init__(self, start=0, **kw):
        super().__init__(status_for=lambda r, u, s: ST(open_=True), **kw); self.n = start

    def __call__(self, url, payload, timeout):
        out = super().__call__(url, payload, timeout)
        if url.endswith('/api/chat'):
            self.n += 1; c = out['message']['content']; out = {**out, 'message': {'content': c.replace('Doctor view', f'Doctor view #{self.n}', 1)}}
        return out

    def rounds(self): return [int(__import__('re').search(r'discussion turn (\d+) of', u).group(1)) for u, _ in self.chats if 'discussion turn' in u]


def table(tmp_path, split='train', cases=(CASE,), seed_of=lambda cid: DO.train_seed(CFG, cid), doc=None, name='t.json'):
    doc = doc or doctor(Noisy())
    recs = [DO.make_record(DO.identity(split, c, doc, 5, seed_of(c['case_id'])), doc.turn(c, [], 1, 5, seed_of(c['case_id'])), {'test': True})
            for c in cases]
    path = tmp_path / name; sha = DO.write_table(path, split, doc, 5, recs, {'test': True})
    return path, sha


class Agent:
    def __init__(self, tag): self.tag = tag

    def sample(self, case, prefix, turn, seed): return {'completion_text': f'{self.tag}: I think B is best supported (turn {turn}).'}


def tree(doc, opening, policy, tag, cache=None):
    return build_tree(CASE, max_agent_turns=5, branching=2, run_seed=CFG['schedule']['seed'], policy_sha256=policy, protocol_sha256='proto',
                      agent=Agent(tag), doctor=doc, stop_rule=stop_reason, final_option=final_answer_option,
                      outcome_fn=lambda c, o: float(o == 'B') if o else None, cache=cache or CallCache(None), opening=opening)


def d1_of(t): return t.nodes[0].prefix[0][3]                             # prefix turns are (speaker, stage, round, text)


def test_training_d1_is_byte_identical_across_arms_and_policies_and_d2_is_per_arm(tmp_path):
    path, sha = table(tmp_path); rec = json.loads(path.read_text())['records'][0]
    outs = []
    for policy, tag, start in (('policy-outcome-only', 'arm1', 0), ('policy-rubric-only', 'arm2', 1000)):
        fake = Noisy(start); doc = doctor(fake); t = tree(doc, DO.OpeningTable(path, sha, 'train', doc, 5), policy, tag, CallCache(tmp_path / f'{tag}.jsonl'))
        assert 1 not in fake.rounds() and 2 in fake.rounds()                 # D1 never generated; D2+ generated by this arm
        outs.append((t, fake))
    (a, fa), (b, fb) = outs
    assert d1_of(a) == d1_of(b) == rec['visible']
    d2 = lambda t: [n.prefix[2][3] for n in t.nodes if n.depth == 2]
    assert set(d2(a)).isdisjoint(d2(b))                                      # later Doctor turns are each arm's own samples


